var detectSite = function() {
  var host = window.location.hostname
  if (host.includes('jseek.co'))          return SITE_CONFIGS.jseek
  if (host.includes('linkedin.com'))      return SITE_CONFIGS.linkedin
  if (host.includes('jobright.ai'))       return SITE_CONFIGS.jobright
  if (host.includes('indeed.com'))        return SITE_CONFIGS.indeed
  if (host.includes('glassdoor.com'))     return SITE_CONFIGS.glassdoor
  if (host.includes('greenhouse.io'))     return SITE_CONFIGS.greenhouse
  if (host.includes('lever.co'))          return SITE_CONFIGS.lever
  if (host.includes('myworkdayjobs.com')) return SITE_CONFIGS.workday
  if (host.includes('ziprecruiter.com'))  return SITE_CONFIGS.ziprecruiter
  if (host.includes('builtin'))           return SITE_CONFIGS.builtin
  if (host.includes('wellfound.com'))     return SITE_CONFIGS.wellfound
  if (host.includes('dice.com'))          return SITE_CONFIGS.dice
  return null
}
